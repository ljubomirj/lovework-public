#!/usr/bin/env python3
"""hone_board.py — the refined GO view: what the re-reading loop knows that the
crawl-time score did not.

LJ, 2026-10-18: *"The initial GO list I saw on Sat after the principal lj
crawl bears no resemblance to the list as it is now only 12h since the end of
the full crawl."* The refinement was real, but it lived in scattered review
notes while the ranking the principal reads stayed the crawl's. This board is
that ranking joined with the review ledger — one file, regenerated by every
draining tick run, so the honed state is one click away instead of forty.

A **projection, never a verdict** (ch43 §11: a review is not a re-verdict):
the wiki index keeps the decisions it keeps, and this file says what the
re-reading found *beside* them. Regenerating it is idempotent; nothing reads
it as an authority — `loop/reviews.jsonl` is the ledger, the packs hold the
notes, and this is their readable join.

    hone_board.py --profile lj     # regenerate state/example/loop/hone-board.md
"""
from __future__ import annotations

import argparse
import os
import sys
from datetime import date, datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config  # noqa: E402  (path set above, matching the sibling modules)

#: The board's name inside `state/<p>/loop/` — the loop's own residue, like
#: the drafts and the envelopes, so it never lands in the sealed crawl tree.
HONE_BOARD_NAME = "hone-board.md"

#: How many waiting rows to list before "+N more". The rotation's order is the
#: information; the tail is the same fact repeated.
WAITING_CAP = 30


def board_rows(state_root: Path, profile: str,
               today: date | None = None) -> list[dict]:
    """One row per live GO, joined with its latest review.

    The reads are the same authorities the decider uses — `current_view` for
    which GOs are still live, `pack_index`/`pack_for` for the pack, the loop's
    own `reviews.jsonl` for the re-read — so the board cannot disagree with
    the queue about what is current.
    """
    from application_packs import dossier_entry, pack_for, pack_index
    from tick import read_reviews
    from wiki_store import WikiStore

    today = today or date.today()
    store = WikiStore(root=state_root / "wiki", create=False)
    _current, fresh = store.current_view(today=today)
    packs = pack_index(profile, root=state_root / "applications")
    reviews = read_reviews(state_root)

    rows: list[dict] = []
    for e in fresh:
        if e.decision != "GO":
            continue
        pack = pack_for(packs, e.org_name, e.title,
                        e.original_url or e.url or "")
        review = reviews.get(pack.name) if pack else None
        primary = ""
        if pack is not None:
            rebuilt = dossier_entry(pack)
            if rebuilt is not None:
                entry, _identity = rebuilt
                primary = "retained" if entry.primary_content_hash \
                    else "not retained"
        rows.append({
            "org": e.org_name, "role": e.title,
            "url": e.original_url or e.url or "",
            "score": float(e.score or 0.0),
            "pack": pack,
            "primary": primary,
            "reviewed": bool(review),
            "new_score": (float(review["new_score"])
                          if review and review.get("new_score") is not None
                          else None),
            "new_decision": (review.get("new_decision")
                             if review else None) or "",
            "delta": review.get("delta") if review else None,
            "moved": bool(review and review.get("moved")),
            "published": bool(review and review.get("published")),
            "note": (review.get("note") if review else "") or "",
            "count": int((review or {}).get("count", 0)),
            "last": str((review or {}).get("at") or "")[:10],
        })
    return rows


def enacted_rows(state_root: Path) -> list[dict]:
    """Review-ruled DROPs already enacted: the pack now sits in `leads/`.

    LJ, 2026-10-18: *"So DROP should be acted on and that lead moved from
    applications/ to leads/ … that's a plus, not a minus."* Once enacted, the
    GO leaves the view and this board's tables — so the board owes the reader
    the list of what left and why, derived (not stored): a review row whose
    pack directory exists under `leads/` is an enacted DROP.
    """
    from application_packs import pack_parts
    from tick import read_reviews

    out: list[dict] = []
    leads = state_root / "leads"
    for name, row in read_reviews(state_root).items():
        pack = leads / name
        if not pack.is_dir():
            continue
        if str(row.get("new_decision") or "").upper() != "DROP":
            continue
        org, role = pack_parts(pack)
        out.append({"org": org, "role": role, "pack": name,
                    "last": str(row.get("at") or "")[:10],
                    "old_score": row.get("old_score"),
                    "new_score": row.get("new_score")})
    out.sort(key=lambda r: (r["last"], r["org"], r["role"]), reverse=True)
    return out


#: How many enacted rows to list — the ledger (`leads/retired.jsonl`) is the
#: full record; the board shows the recent edge of it.
ENACTED_CAP = 15


def _dashboard_path(profile: str, pack: Path, leaf: str) -> str:
    """The dashboard's own URL form for a file inside a pack (AGENTS.md §8)."""
    return f"/principals/{profile}/applications/{pack.name}/{leaf}"


def render_board(rows: list[dict], *, profile: str,
                 generated_at: str, enacted: list[dict] | None = None) -> str:
    """The board as markdown. Moved first — that is the news."""
    moved = sorted((r for r in rows if r["moved"]),
                   key=lambda r: (r["last"], r["org"], r["role"]), reverse=True)
    waiting = [r for r in rows if not r["moved"]]
    # The rotation's own rank: never-read-without-evidence first, then
    # never-read, then the oldest re-read — the same order the decider ranks
    # reviews by, so the board shows the queue the loop is actually chewing.
    waiting.sort(key=lambda r: (
        0 if not r["reviewed"] and r["primary"] == "not retained"
        else 1 if not r["reviewed"] else 2,
        r["last"], r["org"], r["role"]))

    lines = [f"# Hone board — {profile}", ""]
    lines.append("> The refined GO view: what the re-reading loop knows that the")
    lines.append("> crawl-time score did not. Regenerated by every draining tick run")
    lines.append("> — a projection, never a verdict (docs/43 §11–12); the wiki index")
    lines.append("> keeps the decisions, the packs hold the notes.")
    lines.append("")
    lines.append(f"generated: {generated_at} · GOs on file: {len(rows)} · "
                 f"re-read: {sum(1 for r in rows if r['reviewed'])} · "
                 f"moved: {len(moved)}"
                 + (f" · enacted to leads: {len(enacted)}"
                    if enacted is not None else ""))
    lines.append("")

    if enacted:
        lines.append("## Enacted — moved to leads/ (the SNR gain, newest first)")
        lines.append("")
        lines.append("Re-judged out of the GO set; the pack moved whole, nothing "
                     "deleted:")
        lines.append("")
        shown = enacted[:ENACTED_CAP]
        for r in shown:
            old = r["old_score"] if r["old_score"] is not None else "—"
            new = r["new_score"] if r["new_score"] is not None else "—"
            lines.append(f"- {r['last'] or '—'} · {r['org']} — {r['role']} · "
                         f"{old} → {new} DROP · "
                         f"[pack](/principals/{profile}/leads/{r['pack']}/"
                         f"application_pack.md)")
        if len(enacted) > len(shown):
            lines.append(f"- … and {len(enacted) - len(shown)} more "
                         f"(full record: `leads/retired.jsonl`)")
        lines.append("")

    if moved:
        lines.append("## Moved (newest review first)")
        lines.append("")
        lines.append("| Re-read | Org — Role | Crawl said | Re-read says | Δ | Note |")
        lines.append("|---|---|---|---|---|---|")
        for r in moved:
            delta = r["delta"]
            delta_text = f"{delta:+.1f}" if isinstance(delta, (int, float)) else "—"
            note = (f"[review]({_dashboard_path(profile, r['pack'], 'review.md')})"
                    if r["published"] and r["pack"] else
                    "drafted, not published")
            new = (f"{r['new_score']:.1f} {r['new_decision']}"
                   if r["new_score"] is not None else "—")
            lines.append(f"| {r['last'] or '—'} | {r['org']} — {r['role']} "
                         f"| {r['score']:.1f} GO | {new} | {delta_text} "
                         f"| {note} |")
        lines.append("")

    if waiting:
        lines.append("## Waiting (the rotation's own order)")
        lines.append("")
        shown = waiting[:WAITING_CAP]
        for r in shown:
            if not r["reviewed"]:
                state = ("scored without the advert"
                         if r["primary"] == "not retained" else
                         "never re-read" if r["primary"] else "no dossier")
            else:
                state = f"re-read {r['last']} ({r['count']}×), no move"
            lines.append(f"- {r['org']} — {r['role']} · {r['score']:.1f}/10 · "
                         f"{state}")
        if len(waiting) > len(shown):
            lines.append(f"- … and {len(waiting) - len(shown)} more")
        lines.append("")

    if not rows:
        lines.append("No live GOs on file — the board is empty because the "
                     "index's GO view is.")
    elif not moved:
        lines.append("Nothing has moved (yet): every re-read so far confirmed "
                     "the crawl-time score, or the rotation has not reached "
                     "these GOs.")

    lines.append("")
    lines.append("---")
    lines.append("*`moved` clears `LOVEWORK_REVIEW_MATERIAL_DELTA` (2.0) or changes "
                 "the tier — the measured cross-model spread, so noise does not "
                 "count as news. The re-read runs on the local model; its "
                 "calibration offset is named in each review note.*")
    return "\n".join(lines) + "\n"


def write_board(state_root: Path, profile: str,
                today: date | None = None) -> Path:
    """Regenerate the board atomically. Returns its path."""
    rows = board_rows(state_root, profile, today=today)
    enacted = enacted_rows(state_root)
    generated_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    text = render_board(rows, profile=profile, generated_at=generated_at,
                        enacted=enacted)
    path = state_root / "loop" / HONE_BOARD_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    return path


def _main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", default="lj")
    parser.add_argument("--today", default=None, help="YYYY-MM-DD (testing)")
    args = parser.parse_args(argv)

    today = date.fromisoformat(args.today) if args.today else None
    state_root = config.STATE_DIR / args.profile
    if not (state_root / "wiki").is_dir():
        print(f"no wiki for {args.profile}: {state_root / 'wiki'}", file=sys.stderr)
        return 2
    path = write_board(state_root, args.profile, today=today)
    print(f"{args.profile}: board {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
