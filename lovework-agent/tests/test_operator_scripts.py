SAMPLE_REPORT_FOR_MANUAL = SAMPLE_REPORT


def test_extract_top_gos_picks_highest_scores(tmp_path):
    report = tmp_path / "r.md"
    report.write_text(SAMPLE_REPORT_FOR_MANUAL, encoding="utf-8")
    gos = build_manual._extract_top_gos(report, n=2)
    # Highest score: 9.0 (NoCo, from ## New Listings), then 8.5 (Poolside/Aleph).
    # _extract_top_gos picks GOs by default, so entries in "## New Listings"
    # are treated as GO (the wiki writer only renders GO + MAYBE in that
    # section). NoCo is 9.0, Poolside + Aleph Alpha are 8.5 — top 2 by
    # score should be NoCo + either Poolside or Aleph.
    assert len(gos) == 2
    assert gos[0]["org"] == "NoCo"
    assert gos[0]["score"] == 9.0
    # Second must be 8.5.
    assert gos[1]["score"] == 8.5


