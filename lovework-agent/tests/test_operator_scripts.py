def test_parse_report_extracts_go_sections(tmp_path):
    report = tmp_path / "2026-06-20-lj-general-report.md"
    report.write_text(SAMPLE_REPORT, encoding="utf-8")
    listings = crosscheck.parse_report(report, include_maybe=False)
    # 3 GOs (the DROP is skipped), but only 2 with URL + score; the 3rd has
    # only a score line. All 3 should be parsed.
    orgs = [l["org"] for l in listings]
    assert "Poolside" in orgs
    assert "Aleph Alpha" in orgs
    assert "NoCo" in orgs
    assert "OldOrg" not in orgs  # explicit DROP, not in GO section


def test_parse_report_includes_maybe_when_flagged(tmp_path):
    report = tmp_path / "r.md"
    report.write_text(SAMPLE_REPORT, encoding="utf-8")
    only_go = crosscheck.parse_report(report, include_maybe=False)
    with_maybe = crosscheck.parse_report(report, include_maybe=True)
    # The report has only GO + DROP sections, so the flag shouldn't change anything.
    # (include_maybe only matters when there's a ## MAYBE section.)
    assert len(only_go) == len(with_maybe)


