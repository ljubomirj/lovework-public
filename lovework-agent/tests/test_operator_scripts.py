def test_crosscheck_finds_prior_contact(tmp_path, monkeypatch):
    """A fake applications/ with a Poolside rejection triggers a cross-check."""
    # Seed the wiki with the report in a temp dir, NOT the real one.
    fake_reports = tmp_path / "reports"
    fake_reports.mkdir()
    (fake_reports / "2026-06-20-lj-general-report.md").write_text(SAMPLE_REPORT, encoding="utf-8")
    monkeypatch.setattr(config, "WIKI_REPORTS", fake_reports)
    monkeypatch.setattr(config, "WIKI_ORGS", tmp_path / "orgs")
    monkeypatch.setattr(config, "WIKI_ROOT", tmp_path / "wiki")

    # Seed the applications dir with a fake prior application that includes
    # a rejection marker. Use a unique org name to avoid conflicts with
    # any pre-existing real data.
    org_name = "TestCo"
    app_dir = config.APPLICATIONS_DIR / f"20260419-{org_name}-Some_Role"
    if app_dir.exists():
        import shutil
        shutil.rmtree(app_dir)
    app_dir.mkdir(parents=True)
    txt = app_dir / f"20260419-{org_name}-Some_Role.txt"
    txt.write_text(
        "Applied.\n\nRejection received 2026-05-01: decided not to move forward.",
        encoding="utf-8",
    )

    # Import the actual PriorContact / PriorApplication from history.
    from history import PriorContact, PriorApplication

    # Stub Gmail so we don't depend on google_api.py.
    monkeypatch.setattr(crosscheck, "scan_history", lambda org, use_gmail: (
        PriorContact(
            org=org_name,
            applications=[PriorApplication(
                date="2026-04-19", company=org_name, role="Some Role",
                path=app_dir, txt_path=txt, has_rejection=True, rejection_date="2026-05-01",
            )],
            gmail_events=[],
        ) if org == org_name else PriorContact(org=org)
    ))

    found = crosscheck.cross_check(
        org_name, "Member of Engineering (Pre-training / Data Acquisition)",
        8.5, "https://testco.example/x", today="2026-06-23", wiki=None,
    )
    assert found is not None
    assert found["has_rejection"] is True
    assert "rejection" in found["summary"].lower()
    assert "Some Role" in found["summary"]


